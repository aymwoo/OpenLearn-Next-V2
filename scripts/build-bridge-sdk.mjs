#!/usr/bin/env node
/**
 * build-bridge-sdk.mjs
 *
 * 将 packages/bridge-sdk/src/bridge.js 同步编译并注入到 server/utils/bridge-sdk.ts
 * 消除 server/utils/ 下维护 780+ 行裸写模板字符串的技术债务。
 *
 * 关键约定：**packages/bridge-sdk/src/bridge.js 是唯一真相源**，
 * server/utils/bridge-sdk.ts 是它的生成物。任何时候两者不一致，
 * 说明生成物没跟着源码刷新 —— 而构建（pnpm build）会先重新生成，
 * 于是「仓库里校验的」与「真正发布出去的」就会是两份代码。
 * server/__tests__/bridge-sdk-generated.test.ts 会持续盯住这一点。
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

export const BRIDGE_SOURCE_FILE = path.join(rootDir, 'packages/bridge-sdk/src/bridge.js');
export const BRIDGE_TARGET_FILE = path.join(rootDir, 'server/utils/bridge-sdk.ts');

/**
 * 把 bridge.js 的源码转成 server/utils/bridge-sdk.ts 的完整内容（纯函数）。
 * 单独导出是为了让测试能直接比对「生成物 vs 源码」，不必真的落盘。
 */
export function renderBridgeSdkTs(rawCode) {
  // 仅转义反引号与模板插值 ${，保留原生的 JavaScript 转义符
  const sanitizedCode = rawCode.replace(/`/g, '\\`').replace(/\${/g, '\\${');

  return `/**
 * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
 * Source: packages/bridge-sdk/src/bridge.js
 * Generated by: scripts/build-bridge-sdk.mjs
 *
 * LMS Bridge SDK — 课件与宿主 iframe 通信桥接代码。
 *
 * 服务端：注入到课件 HTML 中（injectLmsSdk），或通过 /bridge.js 路由提供。
 * 前端白板：wrapSrcDocWithBridge() 中通过 <script src="/bridge.js"> 引用。
 */

export const BRIDGE_SDK_CODE = \`${sanitizedCode}\`;
`;
}

/** 重新生成 server/utils/bridge-sdk.ts */
export function buildBridgeSdk() {
  if (!fs.existsSync(BRIDGE_SOURCE_FILE)) {
    console.error(`[build-bridge-sdk] Error: Source file not found: ${BRIDGE_SOURCE_FILE}`);
    process.exit(1);
  }

  const rawCode = fs.readFileSync(BRIDGE_SOURCE_FILE, 'utf8');
  fs.writeFileSync(BRIDGE_TARGET_FILE, renderBridgeSdkTs(rawCode), 'utf8');
  console.log(
    `[build-bridge-sdk] Successfully compiled packages/bridge-sdk/src/bridge.js (${rawCode.length} bytes) -> server/utils/bridge-sdk.ts`,
  );
}

// 直接执行时才落盘；被 import（例如测试）时只提供纯函数，不产生副作用
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  buildBridgeSdk();
}
