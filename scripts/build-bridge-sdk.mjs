#!/usr/bin/env node
/**
 * build-bridge-sdk.mjs
 *
 * 将 packages/bridge-sdk/src/bridge.js 同步编译并注入到 server/utils/bridge-sdk.ts
 * 消除 server/utils/ 下维护 780+ 行裸写模板字符串的技术债务。
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const sourceFile = path.join(rootDir, 'packages/bridge-sdk/src/bridge.js');
const targetFile = path.join(rootDir, 'server/utils/bridge-sdk.ts');

if (!fs.existsSync(sourceFile)) {
  console.error(`[build-bridge-sdk] Error: Source file not found: ${sourceFile}`);
  process.exit(1);
}

const rawCode = fs.readFileSync(sourceFile, 'utf8');

// 仅转义反引号与模板插值 ${，保留原生的 JavaScript 转义符
const sanitizedCode = rawCode
  .replace(/`/g, '\\`')
  .replace(/\${/g, '\\${');

const outputTs = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
 * Source: packages/bridge-sdk/src/bridge.js
 * Generated by: scripts/build-bridge-sdk.mjs
 *
 * LMS Bridge SDK — 课件与宿主 iframe 通信桥接代码。
 *
 * 服务端：注入到课件 HTML 中（injectLmsSdk），或通过 /bridge.js 路由提供。
 * 前端白板：wrapSrcDocWithBridge() 中通过 <script src="/bridge.js"> 引用。
 */

export const BRIDGE_SDK_CODE = \`${sanitizedCode}\`;
`;

fs.writeFileSync(targetFile, outputTs, 'utf8');
console.log(`[build-bridge-sdk] Successfully compiled packages/bridge-sdk/src/bridge.js (${rawCode.length} bytes) -> server/utils/bridge-sdk.ts`);
