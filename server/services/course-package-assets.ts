/**
 * 课程包（Course Package）资产层。
 *
 * 课程模板必须自带**真实可打开的**样例文件，否则「课件演示」组件的 PDF / PPTX
 * 分支无法被验证：教师在白板上传的课件，其元素数据里存的是
 * `fileUrl: "/uploads/xxxx.pptx"` —— 一个**指向本机 uploads 目录的相对路径**。
 * 课程包把这个路径抽象成 `${asset:<id>}` 占位符，导入时再解析成导入方机器上
 * 真实落盘后的 URL，模板因此可以在任意实例之间搬运。
 *
 * 本文件负责两件事：
 * 1. 生成样例资产（PDF 讲义 / PPTX 课件）——无外部二进制依赖，纯代码产出；
 * 2. 把课程包里的 base64 资产落盘到 uploads 目录并返回可用的 `/uploads/xxx` URL。
 */
