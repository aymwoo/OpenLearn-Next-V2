/** 课程包内允许出现的资产类型（与 /api/upload 保持一致）。 */
export const PACKAGE_ASSET_TYPES = ['pdf', 'pptx'] as const;
export type PackageAssetType = (typeof PACKAGE_ASSET_TYPES)[number];

/** 资产占位符：`${asset:pptx-deck}` → 导入后被替换为真实 /uploads URL。 */
export const ASSET_PLACEHOLDER_PATTERN = /\$\{asset:([A-Za-z0-9_-]+)\}/g;

/** 单个资产落盘后的结果。 */
export interface MaterializedAsset {
  /** 资产在课程包内的唯一 ID（与占位符中的 id 对应）。 */
  id: string;
  /** 落盘后的可访问 URL（相对站点根路径）。 */
  fileUrl: string;
  /** 原始文件名。 */
  fileName: string;
  /** 资产类型（pdf / pptx）。 */
  fileType: PackageAssetType;
  /** 幻灯片 / 页数。 */
  slideCount: number;
}

/**
 * 样例 PDF 讲义。
 *
 * 用 jsPDF 生成 3 页 A4 讲义，**纯 ASCII 内容** —— jsPDF 内置的 Helvetica 是
 * WinAnsi 编码的 base-14 字体，写中文会得到乱码；要正确渲染中文必须内嵌
 * CJK 字体（体积上百 KB，且会依赖宿主机字体路径），不适合作为「人人可复现」
 * 的模板资产。因此讲义正文用英文，课程的中文内容放在课程大纲与白板元素里。
 */
export function buildSamplePdfBuffer(): Buffer {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();

  const drawHeader = (title: string, subtitle: string) => {
    doc.setFillColor(79, 70, 229); // indigo-600
    doc.rect(0, 0, pageWidth, 96, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    doc.text(title, 56, 46);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text(subtitle, 56, 68);
    doc.setTextColor(30, 41, 59);
  };

  const drawBullets = (items: string[], startY: number) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(12);
    let y = startY;
    for (const item of items) {
      const lines = doc.splitTextToSize(item, pageWidth - 130) as string[];
      doc.setFillColor(99, 102, 241);
      doc.circle(64, y - 4, 3, 'F');
      doc.text(lines, 80, y);
      y += lines.length * 16 + 10;
    }
    return y;
  };

  // ── 第 1 页：封面 ────────────────────────────────────────────────────────
  drawHeader('OpenLearn Course Package', 'Sample Handout (PDF) - template asset for the Slides Deck widget');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('Why this file exists', 56, 150);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  const coverIntro = doc.splitTextToSize(
    'The "Slides Deck" (presentation) widget supports three sources: an inline Markdown deck, ' +
      'an uploaded PDF, and an uploaded PPTX. This PDF exercises the uploaded-PDF branch: ' +
      'the template ships the file itself, and the importer re-hosts it on the target ' +
      'instance so the widget can load it without any manual re-upload.',
    pageWidth - 112,
  ) as string[];
  doc.text(coverIntro, 56, 176);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Asset id: asset-sample-handout', 56, 176 + coverIntro.length * 15 + 24);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by the OpenLearn course package template builder.', 56, 176 + coverIntro.length * 15 + 46);

  // ── 第 2 页：组件清单 ────────────────────────────────────────────────────
  doc.addPage();
  drawHeader('Preset components covered', 'Every palette item shipped with the OpenLearn lesson editor');
  drawBullets(
    [
      'presentation - Slides Deck: Markdown deck, plus this PDF and the companion PPTX.',
      'quiz - Interactive Quiz: question + four options with a correct answer key.',
      'code-sandbox - Code Editor: a runnable JavaScript snippet.',
      'math-graph - Math Grapher: a function expression to plot.',
      'html-applet - Interactive Courseware: an inline HTML applet rendered in a sandboxed iframe.',
      'assignment - Assignment: title + description, bound to the lesson for student submissions.',
      'rollcall - Random Picker: random student selection with teacher-only evaluation.',
      'hello-world - Greeting plugin: the smallest possible plugin-backed widget.',
      'text / rectangle / circle - base canvas primitives used to annotate the board.',
    ],
    150,
  );

  // ── 第 3 页：导入说明 ────────────────────────────────────────────────────
  doc.addPage();
  drawHeader('How to import', 'Three steps, all from the course library toolbar');
  drawBullets(
    [
      'Download the course package: the course library toolbar exposes "Download course template".',
      'Open the file: it is a single self-contained JSON document (assets are base64 encoded inline).',
      'Import the package: drop the JSON onto the import dialog. Lesson, timeline and every ' +
        'whiteboard element are written in a single transaction; a failure rolls the whole thing back.',
    ],
    150,
  );
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text('OpenLearn Next - Educational OS', 56, 780);

  return Buffer.from(doc.output('arraybuffer'));
}

/**
 * 生成一张幻灯片（OOXML `p:sp` 文本框）。
 *
 * 坐标单位为 EMU（1 pt = 12700 EMU），画布 16:9 = 12192000 x 6858000。
 */
function buildSlideShape(opts: {
  id: number;
  name: string;
  x: number;
  y: number;
  width: number;
  height: number;
  text: string;
  fontSize: number;
  bold?: boolean;
  color?: string;
}): string {
  const { id, name, x, y, width, height, text, fontSize, bold, color = '1E293B' } = opts;
  const paragraphs = text
    .split('\n')
    .map(
      (line, idx) =>
        `<a:p><a:pPr algn="l"/><a:r><a:rPr lang="zh-CN" altLang="en-US" sz="${fontSize}" b="${bold ? 1 : 0}" dirty="0">` +
        `<a:solidFill><a:srgbClr val="${color}"/></a:solidFill></a:rPr><a:t>${escapeXml(line)}</a:t></a:r></a:p>`,
    )
    .join('');
  return (
    `<p:sp><p:nvSpPr><p:cNvPr id="${id}" name="${escapeXml(name)}"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>` +
    `<p:spPr><a:xfrm><a:off x="${x}" y="${y}"/><a:ext cx="${width}" cy="${height}"/></a:xfrm>` +
    `<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr>` +
    `<p:txBody><a:bodyPr wrap="square" rtlCol="0"><a:normAutofit/></a:bodyPr><a:lstStyle/>${paragraphs}</p:txBody></p:sp>`
  );
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

