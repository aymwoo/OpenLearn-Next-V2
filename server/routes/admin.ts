import semver from 'semver';
import { kernelContainer } from '../../packages/core/kernel/index.js';
import { PLATFORM_VERSION } from '../../packages/core/version.js';
import { randomId } from '../utils/id.js';
import { requireAuth } from '../middleware/auth.js';
import type { ServerContext } from '../context.js';
import { sendSafeError } from '../utils/error-handler.js';
import { seedDemoData, DEMO_IDS, DEMO_TEACHER } from '../services/demo-data.js';
import { getEncryptionKeyStatus } from '../../packages/core/di/api-key-crypto.js';
import { RosterService } from '../services/roster-service.js';

export function registerAdminRoutes(ctx: ServerContext) {
  const { app } = ctx;

  /**
   * 加密密钥来源。只告诉管理员是不是自动生成的钥匙，不返回密钥或密文。
   */
  app.get('/api/system/encryption-status', requireAuth('administrator'), (_req, res) => {
    try {
      const status = getEncryptionKeyStatus();
      res.json({
        source: status.source,
        autoGenerated: status.autoGenerated,
        warning: status.warning,
      });
    } catch (e: any) {
      sendSafeError(res, e);
    }
  });

  /**
   * 平台官方源版本更新检查 (npm registry)
   */
  app.get('/api/system/check-upgrade', requireAuth('teacher', 'administrator'), async (_req, res) => {
    try {
      const currentVersion = PLATFORM_VERSION;
      let latestVersion = currentVersion;
      let publishTime: string | null = null;

      const registries = [
        'https://registry.npmjs.org/openlearn-next/latest',
        'https://registry.npmmirror.com/openlearn-next/latest',
      ];

      for (const url of registries) {
        try {
          const controller = new AbortController();
          const timer = setTimeout(() => controller.abort(), 3500);
          const response = await fetch(url, { signal: controller.signal });
          clearTimeout(timer);
          if (response.ok) {
            const data: any = await response.json();
            if (data.version) {
              latestVersion = data.version;
              publishTime = data.publish_time || null;
              break;
            }
          }
        } catch {}
      }

      const hasUpdate = semver.gt(latestVersion, currentVersion);

      res.json({
        success: true,
        currentVersion,
        latestVersion,
        hasUpdate,
        publishTime,
        upgradeCommands: {
          npx: 'npx openlearn-next@latest',
          npm: 'npm i -g openlearn-next@latest',
          git: 'git pull && pnpm build && pnpm start',
        },
      });
    } catch (e: any) {
      sendSafeError(res, e);
    }
  });

  /**
   * 兼容端点：新手引导（HelpTour）仍在调用。
   *
   * 2026-10-03 起改为委托给 `server/services/demo-data.ts` 的正式播种实现 ——
   * 旧实现有两个安全问题：
   *   1. `lessonId` 取自 `SELECT id FROM lessons LIMIT 1`，**劫持真实课程**；
   *   2. 学生按 `student_number`（S001…）复用，可能把**真实学生**链接进演示班级。
   * 新实现自建课程与学生，并把创建的每一行登记进 `demo_data_registry`，
   * 使"一键清理"可以精确删除而不误伤真实数据。
   *
   * 响应字段保持向后兼容（HelpTour 依赖 classId / scheduleId / lessonId）。
   */
  app.post('/api/admin/seed-demo', requireAuth('administrator'), (req, res) => {
    try {
      const status = seedDemoData(kernelContainer.db);
      res.json({
        success: true,
        classId: DEMO_IDS.primaryClass,
        scheduleId: DEMO_IDS.schedule,
        lessonId: DEMO_IDS.lesson,
        result: { ...status, credentials: DEMO_TEACHER },
      });
    } catch (e: any) {
      sendSafeError(res, e);
    }
  });

  app.post('/api/classes/import', requireAuth('teacher', 'administrator'), (req, res) => {
    try {
      const { classes } = req.body;
      if (!classes || !Array.isArray(classes)) {
        return res.status(400).json({ error: 'Invalid payload: classes must be an array' });
      }

      const db = kernelContainer.db;
      const rosterService = new RosterService();

      const ownerId = (req as any).session?.userId || null;
      const insertClass = db.prepare(
        'INSERT INTO classes (id, name, description, owner_user_id, created_at) VALUES (?, ?, ?, ?, ?)',
      );

      const imported: any[] = [];
      /** 汇总本次导入新产生的初始密码，供教师分发给学生登录 */
      const credentials: { student_number: string; name: string; initial_password: string }[] = [];

      // DATA-INT-01: 整批导入包事务 —— 任一学生落库失败整体回滚，不残留半截班级。
      // 学生入库复用 RosterService.importStudents（去重 / 学号 / 密码的唯一实现），
      // better-sqlite3 的嵌套事务在此以 SAVEPOINT 语义嵌套，回滚依然整体生效。
      const importTx = db.transaction(() => {
        for (const cls of classes) {
          const clsName = cls.name || cls.className;
          const clsDesc = cls.description || cls.classDescription || '';
          if (!clsName) continue;

          const classId = randomId();
          insertClass.run(classId, clsName, clsDesc, ownerId, Date.now());

          const { results, created } = rosterService.importStudents(cls.students || [], { classId });

          for (const r of results) {
            if (r.created && r.initial_password) {
              credentials.push({
                student_number: r.student_number,
                name: r.name,
                initial_password: r.initial_password,
              });
            }
          }

          imported.push({
            id: classId,
            name: clsName,
            studentsCount: results.length,
            createdCount: created,
          });
        }
      });
      importTx();

      res.json({ success: true, imported, credentials });
    } catch (e: any) {
      sendSafeError(res, e);
    }
  });

  app.post('/api/students/import', requireAuth('teacher', 'administrator'), (req, res) => {
    try {
      const { students } = req.body;
      if (!students || !Array.isArray(students)) {
        return res.status(400).json({ error: 'Invalid payload: students must be an array' });
      }

      const { results, created, existing } = new RosterService().importStudents(students);

      res.json({
        success: true,
        created,
        existing,
        // 兼容旧前端字段名 `new`
        imported: results.map((r) => ({ ...r, new: r.created })),
      });
    } catch (e: any) {
      sendSafeError(res, e);
    }
  });
}
