/**
 * api-key-crypto — canonical AES-256-GCM encryption for secrets at rest.
 *
 * Used for AI Provider API keys and (via class-passcode-crypto) class passcodes.
 * `server/utils/crypto.ts` re-exports this module so those paths cannot drift.
 *
 * ## Key resolution order
 * 1. Non-empty `process.env.ENCRYPTION_KEY` (must be 64 hex chars / 32 bytes)
 * 2. A non-empty `ENCRYPTION_KEY=` line in `.env` (PM2 may set the env var to `''`)
 * 3. `storage/encryption-key` next to `bootstrap-credentials.txt` (mode 0600)
 * 4. First boot with no key: `crypto.randomBytes(32)` written to that file
 *
 * There is no in-memory-only key and no hardcoded default. An env key wins.
 * If it disagrees with the persisted file, startup throws with migration steps.
 * An empty `ENCRYPTION_KEY=` line in `.env` is left untouched.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const ENCRYPTION_KEY_FILE_NAME = 'encryption-key';

export const AUTO_GENERATED_KEY_WARNING =
  '正在使用自动生成的加密密钥（storage/encryption-key，与 bootstrap-credentials.txt 同目录，权限 600）。' +
  '建议设置环境变量 ENCRYPTION_KEY 为该文件中的 64 位 hex，并离线备份该文件。' +
  'site-backup 不包含此文件。丢失后无法解密 AI Provider API Key 与班级临时口令。';

const HEX_64 = /^[0-9a-fA-F]{64}$/;

export type EncryptionKeySource = 'env' | 'env-file' | 'persisted-file' | 'generated-file';

export interface EncryptionKeyStatus {
  source: EncryptionKeySource;
  autoGenerated: boolean;
  warning: string | null;
}

interface ResolvedEncryptionKey extends EncryptionKeyStatus {
  key: Buffer;
}

export interface ResolveEncryptionKeyOptions {
  env?: NodeJS.ProcessEnv;
  cwd?: string;
  storageDir?: string;
}

export class EncryptionKeyInvalidError extends Error {
  readonly code = 'ENCRYPTION_KEY_INVALID';
  constructor(message: string) {
    super(message);
    this.name = 'EncryptionKeyInvalidError';
  }
}

export class EncryptionKeyMismatchError extends Error {
  readonly code = 'ENCRYPTION_KEY_MISMATCH';
  constructor(filePath: string) {
    super(
      `ENCRYPTION_KEY 与已持久化的密钥文件不一致（${filePath}）。\n` +
        '环境变量优先，但已有密文可能是用文件里的密钥加密的。请二选一后重启：\n' +
        '1. 若环境变量才是加密时的钥匙：确认无误后删除该文件，或把它的内容替换成与环境变量完全相同的 64 位 hex。\n' +
        '2. 若文件才是原钥匙：取消 ENCRYPTION_KEY，或把它改成与文件完全相同的值。\n' +
        '不要在两把钥匙之间来回切换。site-backup 不包含该密钥文件，请单独离线备份。',
    );
    this.name = 'EncryptionKeyMismatchError';
  }
}

let cached: ResolvedEncryptionKey | null = null;

export function resetEncryptionKeyCacheForTests(): void {
  cached = null;
}

/**
 * 与 `resolveBootstrapCredentialDir()` 同一套优先级，避免密钥文件和种子口令
 * 写到不同的卷。本文件不引用 db/index，以免和数据库初始化形成循环依赖。
 */
export function resolveEncryptionKeyStorageDir(env: NodeJS.ProcessEnv = process.env, cwd = process.cwd()): string {
  if (env.OPENLEARN_DATA_DIR?.trim()) {
    return path.join(path.resolve(env.OPENLEARN_DATA_DIR.trim()), 'storage');
  }
  if (env.OPENLEARN_DB_PATH?.trim()) {
    return path.join(path.dirname(path.resolve(env.OPENLEARN_DB_PATH.trim())), 'storage');
  }
  return path.join(cwd, 'storage');
}

function normalizeKeyHex(raw: string): string | null {
  let value = raw.trim();
  if (
    (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
    (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
  ) {
    value = value.slice(1, -1).trim();
  }
  if (!value) return null;
  if (!HEX_64.test(value)) {
    throw new EncryptionKeyInvalidError(
      'ENCRYPTION_KEY 必须是 64 位十六进制（32 字节）。请重新设置，不要使用短密钥或占位符。',
    );
  }
  return value.toLowerCase();
}

function readProcessEnvKey(env: NodeJS.ProcessEnv): string | null {
  const raw = env.ENCRYPTION_KEY;
  if (raw == null || raw.trim() === '') return null;
  return normalizeKeyHex(raw);
}

function readDotEnvKey(cwd: string): string | null {
  const envPath = path.resolve(cwd, '.env');
  if (!fs.existsSync(envPath)) return null;
  let content = '';
  try {
    content = fs.readFileSync(envPath, 'utf8');
  } catch {
    return null;
  }
  const match = content.match(/^ENCRYPTION_KEY=(.*)$/m);
  if (!match) return null;
  return normalizeKeyHex(match[1] ?? '');
}

function keyFilePath(storageDir: string): string {
  return path.join(storageDir, ENCRYPTION_KEY_FILE_NAME);
}

function chmodKeyFile(filePath: string): void {
  try {
    fs.chmodSync(filePath, 0o600);
  } catch (err) {
    throw new Error(
      `无法将 ${filePath} 的权限设为 0600（${err instanceof Error ? err.message : err}）。已拒绝继续使用该密钥文件。`,
    );
  }
}

function readKeyFile(filePath: string): string | null {
  if (!fs.existsSync(filePath)) return null;
  const normalized = normalizeKeyHex(fs.readFileSync(filePath, 'utf8'));
  if (!normalized) {
    throw new EncryptionKeyInvalidError(
      `密钥文件 ${filePath} 是空的。请删掉它，或写入原来的 64 位 hex。不要让系统另造一把钥匙。`,
    );
  }
  chmodKeyFile(filePath);
  return normalized;
}

function keysEqual(left: string, right: string): boolean {
  return crypto.timingSafeEqual(Buffer.from(left, 'hex'), Buffer.from(right, 'hex'));
}

function persistGeneratedKey(filePath: string, generated: string): string {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  try {
    fs.writeFileSync(filePath, `${generated}\n`, { mode: 0o600, flag: 'wx' });
  } catch (err: unknown) {
    const code = err && typeof err === 'object' && 'code' in err ? String((err as { code?: string }).code) : '';
    if (code === 'EEXIST') {
      const existing = readKeyFile(filePath);
      if (!existing) {
        throw new EncryptionKeyInvalidError(`密钥文件 ${filePath} 已存在但无法读取。`);
      }
      return existing;
    }
    throw new Error(
      `无法把自动生成的加密密钥写入 ${filePath}。已拒绝只放在内存里的临时密钥，否则重启后无法解密。` +
        `请检查数据目录权限，或设置 ENCRYPTION_KEY。原因：${err instanceof Error ? err.message : err}`,
    );
  }
  chmodKeyFile(filePath);
  return generated;
}

function finish(source: EncryptionKeySource, hex: string): ResolvedEncryptionKey {
  const autoGenerated = source === 'persisted-file' || source === 'generated-file';
  return {
    key: Buffer.from(hex, 'hex'),
    source,
    autoGenerated,
    warning: autoGenerated ? AUTO_GENERATED_KEY_WARNING : null,
  };
}

export function resolveEncryptionKey(options: ResolveEncryptionKeyOptions = {}): ResolvedEncryptionKey {
  const env = options.env ?? process.env;
  const cwd = options.cwd ?? process.cwd();
  const storageDir = options.storageDir ?? resolveEncryptionKeyStorageDir(env, cwd);
  const filePath = keyFilePath(storageDir);

  const fromProcess = readProcessEnvKey(env);
  const fromDotEnv = fromProcess ? null : readDotEnvKey(cwd);
  const configured = fromProcess ?? fromDotEnv;
  const configuredSource: EncryptionKeySource | null = fromProcess ? 'env' : fromDotEnv ? 'env-file' : null;
  const fileKey = fs.existsSync(filePath) ? readKeyFile(filePath) : null;

  if (configured && fileKey && !keysEqual(configured, fileKey)) {
    throw new EncryptionKeyMismatchError(filePath);
  }
  if (configured && configuredSource) {
    return finish(configuredSource, configured);
  }
  if (fileKey) {
    return finish('persisted-file', fileKey);
  }

  const generated = crypto.randomBytes(32).toString('hex');
  try {
    const stored = persistGeneratedKey(filePath, generated);
    return finish(stored === generated ? 'generated-file' : 'persisted-file', stored);
  } catch (err) {
    if (err instanceof EncryptionKeyInvalidError || err instanceof EncryptionKeyMismatchError) throw err;
    if (err instanceof Error && err.message.includes('临时密钥')) throw err;
    throw new Error(
      `无法把自动生成的加密密钥写入 ${filePath}。已拒绝只放在内存里的临时密钥，否则重启后无法解密。` +
        `请检查数据目录权限，或设置 ENCRYPTION_KEY。原因：${err instanceof Error ? err.message : err}`,
    );
  }
}

function ensureEncryptionKey(): ResolvedEncryptionKey {
  if (!cached) cached = resolveEncryptionKey();
  return cached;
}

export function getEncryptionKey(): Buffer {
  return ensureEncryptionKey().key;
}

export function getEncryptionKeyStatus(): EncryptionKeyStatus {
  const resolved = ensureEncryptionKey();
  return {
    source: resolved.source,
    autoGenerated: resolved.autoGenerated,
    warning: resolved.warning,
  };
}

export function formatEncryptionKeyBanner(status: Pick<EncryptionKeyStatus, 'warning'>): string | null {
  if (!status.warning) return null;
  return [
    '[SECURITY] ============================================================',
    `[SECURITY] ${status.warning}`,
    '[SECURITY] ============================================================',
  ].join('\n');
}

export function logEncryptionKeyStartupWarning(log: (message: string) => void = console.warn): void {
  const banner = formatEncryptionKeyBanner(getEncryptionKeyStatus());
  if (banner) log(banner);
}

export function encryptApiKey(plaintext: string): string {
  if (!plaintext) return '';
  const key = getEncryptionKey();
  const iv = crypto.randomBytes(16);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const encrypted = Buffer.concat([cipher.update(plaintext, 'utf-8'), cipher.final()]);
  const authTag = cipher.getAuthTag();
  return `${iv.toString('hex')}:${authTag.toString('hex')}:${encrypted.toString('hex')}`;
}

/** 判断字符串是否形如 `iv:authTag:ciphertext`（三段十六进制）。 */
export function looksLikeCiphertext(value: string): boolean {
  const parts = (value || '').split(':');
  if (parts.length !== 3) return false;
  return parts.every((p) => p.length > 0 && /^[0-9a-fA-F]+$/.test(p));
}

export function decryptApiKey(encrypted: string): string {
  if (!encrypted) return '';
  // 明文（未加密或旧数据）：直接返回
  const parts = encrypted.split(':');
  if (parts.length !== 3) return encrypted;
  try {
    const key = getEncryptionKey();
    const iv = Buffer.from(parts[0], 'hex');
    const authTag = Buffer.from(parts[1], 'hex');
    const ciphertext = Buffer.from(parts[2], 'hex');
    const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
    decipher.setAuthTag(authTag);
    return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf-8');
  } catch {
    // V7 修复：解密失败 fail-closed（此前把密文当明文 Bearer 继续用，
    // 密文会被打到上游 Authorization 头且误导排障）。调用方应捕获并报 500。
    const err: any = new Error('Failed to decrypt API key (ENCRYPTION_KEY mismatch or corrupted data)');
    err.status = 500;
    throw err;
  }
}
