import { afterEach, describe, expect, it } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  AUTO_GENERATED_KEY_WARNING,
  ENCRYPTION_KEY_FILE_NAME,
  EncryptionKeyInvalidError,
  EncryptionKeyMismatchError,
  formatEncryptionKeyBanner,
  resolveEncryptionKey,
} from '../api-key-crypto.js';

const dirs: string[] = [];

function tempDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'openlearn-key-'));
  dirs.push(dir);
  return dir;
}

function hexKey(): string {
  return crypto.randomBytes(32).toString('hex');
}

afterEach(() => {
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

describe('ENCRYPTION_KEY 解析', () => {
  it('源码里没有写死的 64 位 hex 默认密钥', () => {
    const src = fs.readFileSync(path.resolve(process.cwd(), 'packages/core/di/api-key-crypto.ts'), 'utf8');
    expect(src).not.toMatch(/[0-9a-fA-F]{64}/);
  });

  it('未设置时生成 64 位 hex 并写入 storage/encryption-key（0600），重启后仍是同一把', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    const first = resolveEncryptionKey({ env: {}, cwd: root, storageDir });
    expect(first.source).toBe('generated-file');
    expect(first.autoGenerated).toBe(true);
    expect(first.warning).toContain('自动生成');
    expect(first.key).toHaveLength(32);

    const filePath = path.join(storageDir, ENCRYPTION_KEY_FILE_NAME);
    const onDisk = fs.readFileSync(filePath, 'utf8').trim();
    expect(onDisk).toMatch(/^[0-9a-f]{64}$/);
    expect(fs.statSync(filePath).mode & 0o777).toBe(0o600);
    expect(onDisk).toBe(first.key.toString('hex'));

    const second = resolveEncryptionKey({ env: {}, cwd: root, storageDir });
    expect(second.source).toBe('persisted-file');
    expect(second.autoGenerated).toBe(true);
    expect(second.key.equals(first.key)).toBe(true);
  });

  it('两次独立生成的钥匙不同', () => {
    const a = resolveEncryptionKey({ env: {}, cwd: tempDir(), storageDir: path.join(tempDir(), 'storage') });
    const b = resolveEncryptionKey({ env: {}, cwd: tempDir(), storageDir: path.join(tempDir(), 'storage') });
    expect(a.key.equals(b.key)).toBe(false);
  });

  it('环境变量优先，且不会把钥匙再写进数据目录', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    const configured = hexKey();
    const resolved = resolveEncryptionKey({
      env: { ENCRYPTION_KEY: configured.toUpperCase() },
      cwd: root,
      storageDir,
    });
    expect(resolved.source).toBe('env');
    expect(resolved.autoGenerated).toBe(false);
    expect(resolved.warning).toBeNull();
    expect(resolved.key.toString('hex')).toBe(configured);
    expect(fs.existsSync(path.join(storageDir, ENCRYPTION_KEY_FILE_NAME))).toBe(false);
  });

  it('process.env 为空时读取 .env，且空的 ENCRYPTION_KEY= 行不会被覆盖', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    const configured = hexKey();
    fs.writeFileSync(path.join(root, '.env'), `OTHER=1\nENCRYPTION_KEY="${configured}"\n`);
    const fromFile = resolveEncryptionKey({ env: { ENCRYPTION_KEY: '' }, cwd: root, storageDir });
    expect(fromFile.source).toBe('env-file');
    expect(fromFile.key.toString('hex')).toBe(configured);
    expect(fs.existsSync(path.join(storageDir, ENCRYPTION_KEY_FILE_NAME))).toBe(false);

    const emptyRoot = tempDir();
    const emptyEnv = path.join(emptyRoot, '.env');
    fs.writeFileSync(emptyEnv, 'ENCRYPTION_KEY=\nOTHER=1\n');
    const generated = resolveEncryptionKey({
      env: { ENCRYPTION_KEY: '' },
      cwd: emptyRoot,
      storageDir: path.join(emptyRoot, 'storage'),
    });
    expect(generated.autoGenerated).toBe(true);
    expect(fs.readFileSync(emptyEnv, 'utf8')).toBe('ENCRYPTION_KEY=\nOTHER=1\n');
  });

  it('环境变量与已持久化的钥匙不一致时拒绝启动，并保留原文件', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    fs.mkdirSync(storageDir, { recursive: true });
    const fileKey = hexKey();
    const envKey = hexKey();
    const filePath = path.join(storageDir, ENCRYPTION_KEY_FILE_NAME);
    fs.writeFileSync(filePath, `${fileKey}\n`, { mode: 0o644 });

    let caught: unknown;
    try {
      resolveEncryptionKey({ env: { ENCRYPTION_KEY: envKey }, cwd: root, storageDir });
    } catch (err) {
      caught = err;
    }
    expect(caught).toBeInstanceOf(EncryptionKeyMismatchError);
    const message = caught instanceof Error ? caught.message : '';
    expect(message).toContain('二选一');
    expect(message).toContain('单独离线备份');
    expect(message).not.toContain(fileKey);
    expect(message).not.toContain(envKey);
    expect(fs.readFileSync(filePath, 'utf8').trim()).toBe(fileKey);
  });

  it('长度不对的环境变量直接报错，不另造钥匙', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    expect(() => resolveEncryptionKey({ env: { ENCRYPTION_KEY: 'abcd' }, cwd: root, storageDir })).toThrow(
      EncryptionKeyInvalidError,
    );
    expect(fs.existsSync(path.join(storageDir, ENCRYPTION_KEY_FILE_NAME))).toBe(false);
  });

  it('已有钥匙文件权限过宽时收紧到 0600', () => {
    const root = tempDir();
    const storageDir = path.join(root, 'storage');
    fs.mkdirSync(storageDir, { recursive: true });
    const filePath = path.join(storageDir, ENCRYPTION_KEY_FILE_NAME);
    const fileKey = hexKey();
    fs.writeFileSync(filePath, `${fileKey}\n`, { mode: 0o644 });
    const resolved = resolveEncryptionKey({ env: {}, cwd: root, storageDir });
    expect(resolved.key.toString('hex')).toBe(fileKey);
    expect(fs.statSync(filePath).mode & 0o777).toBe(0o600);
  });

  it('写不进数据目录时拒绝使用只活在内存里的临时密钥', () => {
    const root = tempDir();
    const blocker = path.join(root, 'not-a-directory');
    fs.writeFileSync(blocker, 'x');
    expect(() => resolveEncryptionKey({ env: {}, cwd: root, storageDir: blocker })).toThrow(/临时密钥/);
  });

  it('自动生成时的启动警告点明要设置 ENCRYPTION_KEY 并离线备份', () => {
    const banner = formatEncryptionKeyBanner({ warning: AUTO_GENERATED_KEY_WARNING });
    expect(banner).toContain('[SECURITY]');
    expect(banner).toContain('自动生成');
    expect(banner).toContain('ENCRYPTION_KEY');
    expect(banner).toContain('离线备份');
    expect(banner).toContain('storage/encryption-key');
    expect(banner).not.toMatch(/[0-9a-f]{64}/);
    expect(formatEncryptionKeyBanner({ warning: null })).toBeNull();
  });
});
